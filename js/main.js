const languageLabels = {
  "en-us": "English",
  "zh-cn": "简体中文",
  "zh-hk": "繁體中文"
};

const supportedLanguages = Object.keys(translations);
const defaultLanguage = "zh-hk";

function getSavedLanguage() {
  const savedLanguage = localStorage.getItem("appLan");
  return supportedLanguages.includes(savedLanguage)
    ? savedLanguage
    : defaultLanguage;
}

function applyLanguage(language) {
  const selectedLanguage = supportedLanguages.includes(language)
    ? language
    : defaultLanguage;

  const dictionary = translations[selectedLanguage];

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;

    if (dictionary[key] !== undefined) {
      element.textContent = dictionary[key];
    }
  });

  document.documentElement.lang =
    selectedLanguage === "en-us"
      ? "en"
      : selectedLanguage === "zh-cn"
        ? "zh-CN"
        : "zh-HK";

  const currentLanguageLabel = document.querySelector(".language-current");

  if (currentLanguageLabel) {
    currentLanguageLabel.textContent = languageLabels[selectedLanguage];
  }

  document.querySelectorAll("[data-language]").forEach((button) => {
    const isActive = button.dataset.language === selectedLanguage;

    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-checked", String(isActive));
  });

  localStorage.setItem("appLan", selectedLanguage);
}

function closeLanguageMenu() {
  const switcher = document.querySelector(".language-switcher");
  const button = document.querySelector(".language-button");

  if (switcher) {
    switcher.classList.remove("is-open");
  }

  if (button) {
    button.setAttribute("aria-expanded", "false");
  }
}

function initialiseLanguageSwitcher() {
  const switcher = document.querySelector(".language-switcher");
  const button = document.querySelector(".language-button");

  if (!switcher || !button) {
    applyLanguage(getSavedLanguage());
    return;
  }

  button.addEventListener("click", (event) => {
    event.stopPropagation();

    const isOpen = switcher.classList.toggle("is-open");
    button.setAttribute("aria-expanded", String(isOpen));
  });

  document.querySelectorAll("[data-language]").forEach((languageButton) => {
    languageButton.addEventListener("click", () => {
      applyLanguage(languageButton.dataset.language);
      closeLanguageMenu();
    });
  });

  document.addEventListener("click", (event) => {
    if (!switcher.contains(event.target)) {
      closeLanguageMenu();
    }
  });

  applyLanguage(getSavedLanguage());
}

function initialiseMobileMenu() {
  const menuButton = document.querySelector(
    ".menu-toggle, .mobile-menu-button, [data-menu-toggle]"
  );

  const navigation = document.querySelector(
    ".main-navigation, .site-navigation, .header-navigation"
  );

  if (!menuButton || !navigation) {
    return;
  }

  const closeMenu = () => {
    navigation.classList.remove("is-open");
    menuButton.classList.remove("is-open");
    menuButton.setAttribute("aria-expanded", "false");
  };

  menuButton.addEventListener("click", () => {
    const isOpen = navigation.classList.toggle("is-open");

    menuButton.classList.toggle("is-open", isOpen);
    menuButton.setAttribute("aria-expanded", String(isOpen));
  });

  navigation.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", closeMenu);
  });

  window.addEventListener("resize", () => {
    if (window.innerWidth > 980) {
      closeMenu();
    }
  });

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") {
      closeMenu();
      closeLanguageMenu();
    }
  });
}

function updateCurrentYear() {
  const yearElement = document.querySelector(
    "[data-current-year], #current-year"
  );

  if (yearElement) {
    yearElement.textContent = new Date().getFullYear();
  }
}

function initialisePage() {
  initialiseLanguageSwitcher();
  initialiseMobileMenu();
  updateCurrentYear();

  console.log(
    "[RWA homepage] Initialised with language:",
    localStorage.getItem("appLan")
  );
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", initialisePage);
} else {
  initialisePage();
}
